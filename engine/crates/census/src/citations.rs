//! The names of the original the engine cites: a function of `source/`
//! named in backticks in a comment of a crate's `src/` (`` `unit_kill` ``)
//! or of the app's Swift (`engine/app/Sources`). A citation says the code
//! beside it does that function's job; the census classes it from there.
//! Tests are not citations, and neither is the Swift that `uniffi`
//! generates from the crates' own doc comments.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use crate::{read_text, walk, Error};

/// The first line of a Swift file that `uniffi` generated.
const GENERATED: &str = "autogenerated";

/// Each cited name, and the places that cite it (`sim/src/units.rs:12`,
/// `app/Sources/OpenCEEngineRender/LightPass.swift:40`), in order.
pub type Citations = BTreeMap<String, Vec<String>>;

/// The names among `known` that the engine at `engine` cites.
pub fn collect(engine: &Path, known: &BTreeSet<String>) -> Result<Citations, Error> {
    let mut found = Citations::new();
    let crates = engine.join("crates");
    if crates.is_dir() {
        for path in walk(&crates, &["rs"])? {
            let place = relative(&path, engine)?;
            // (only a crate's src/: its tests and benches are not the engine)
            if place.split('/').nth(1) == Some("src") {
                cite(&read_text(&path)?, &place, "//", known, &mut found);
            }
        }
    }
    let sources = engine.join("app/Sources");
    if sources.is_dir() {
        for path in walk(&sources, &["swift"])? {
            let text = read_text(&path)?;
            if !text
                .lines()
                .next()
                .is_some_and(|line| line.contains(GENERATED))
            {
                cite(&text, &relative(&path, engine)?, "//", known, &mut found);
            }
        }
    }
    Ok(found)
}

/// `path` relative to `engine`, without its leading `crates/`.
fn relative(path: &Path, engine: &Path) -> Result<String, Error> {
    let place = path
        .strip_prefix(engine)
        .map_err(|_| Error::Outside(path.to_owned()))?
        .to_string_lossy()
        .replace('\\', "/");
    Ok(place
        .strip_prefix("crates/")
        .map_or(place.clone(), str::to_owned))
}

/// The citations of one file's comments.
fn cite(text: &str, place: &str, comment: &str, known: &BTreeSet<String>, found: &mut Citations) {
    for (index, line) in text.lines().enumerate() {
        let Some(start) = line.find(comment) else {
            continue;
        };
        for name in quoted(line.get(start..).unwrap_or("")) {
            if known.contains(name) {
                let places = found.entry(name.to_owned()).or_default();
                let here = format!("{place}:{}", index + 1);
                if places.last() != Some(&here) {
                    places.push(here);
                }
            }
        }
    }
}

/// The names in backticks in `text` that could be a function of the
/// original: lower case, digits and underscores, with at least one
/// underscore.
pub fn quoted(text: &str) -> impl Iterator<Item = &str> {
    text.split('`').skip(1).step_by(2).filter(|name| {
        name.contains('_')
            && name.bytes().next().is_some_and(|b| b.is_ascii_lowercase())
            && name
                .bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
    })
}
