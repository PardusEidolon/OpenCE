//! The names of the original the engine cites in its Rust and Swift.

mod common;

use std::collections::BTreeSet;

use common::Tree;
use opence_census::citations::{collect, quoted};
use opence_census::original::Original;

type Failure = Box<dyn std::error::Error>;

fn known(names: &[&str]) -> BTreeSet<String> {
    names.iter().map(|name| (*name).to_owned()).collect()
}

#[test]
fn names_in_backticks_are_quoted() {
    let found: Vec<_> =
        quoted("// Ports `unit_kill` and `units_update`; `Unit`, `x`, `a b_c`").collect();
    assert_eq!(found, ["unit_kill", "units_update"]);
}

#[test]
fn citations_come_from_src_comments_and_swift_but_not_tests_or_the_census() -> Result<(), Failure> {
    let tree = Tree::new("citations")
        .with(
            "crates/sim/src/units.rs",
            "//! Units.\n\n/// `unit_kill`, then `unit_delete`.\nfn kill() {}\nlet s = \"`unit_update`\"; // `unit_update`\n",
        )
        .with("crates/sim/tests/units.rs", "// `unit_spawn`\n")
        .with("crates/census/src/lib.rs", "//! Reads `unit_spawn`'s citations.\n")
        .with("crates/physics/src/a/b.rs", "// `unit_kill` again\n")
        .with(
            "app/Sources/Render/LightPass.swift",
            "/// Does `lights_update`'s job.\nlet x = 1\n",
        )
        .with(
            "app/Sources/Core/opence_ffi.swift",
            "// This file was autogenerated by uniffi\n/// `unit_spawn`\n",
        );
    let names = known(&[
        "unit_kill",
        "unit_delete",
        "unit_update",
        "unit_spawn",
        "lights_update",
    ]);
    let found = collect(tree.root(), &names)?;
    assert_eq!(
        found.keys().map(String::as_str).collect::<Vec<_>>(),
        ["lights_update", "unit_delete", "unit_kill", "unit_update"]
    );
    assert_eq!(
        found["unit_kill"],
        ["physics/src/a/b.rs:1", "sim/src/units.rs:3"]
    );
    assert_eq!(
        found["lights_update"],
        ["app/Sources/Render/LightPass.swift:1"]
    );
    assert_eq!(found["unit_update"], ["sim/src/units.rs:5"]);
    Ok(())
}

#[test]
fn the_runtime_cites_the_functions_it_stands_beside() -> Result<(), Failure> {
    let Some(root) = common::repository() else {
        eprintln!("skipped: no source/");
        return Ok(());
    };
    let original = Original::read(&root.join("source"))?;
    let found = collect(&root.join("engine"), &original.names())?;
    // (the reference map held 159 when the census replaced it; game.wasm
    // now runs the original's own code, and the runtime that hosts it
    // still cites what it stands beside)
    assert!(found.len() >= 20, "only {} cited", found.len());
    for name in [
        "cache_get_tag_instance",
        "system_malloc",
        "physical_memory_verify",
    ] {
        assert!(found.contains_key(name), "{name} is not cited");
    }
    Ok(())
}

#[test]
fn a_call_with_its_arguments_cites_the_name() {
    let found: Vec<_> =
        quoted("// as `matrix4x3_multiply(a, b, out)` does, then `unit_kill()`; `f(x)`").collect();
    assert_eq!(found, ["matrix4x3_multiply", "unit_kill"]);
}
