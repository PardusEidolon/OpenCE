/// The priorities of a unit's speech, lowest first
/// (`global_speech_priority_names`).
pub const SPEECH_PRIORITIES: [&str; 11] = [
    "none",
    "idle",
    "pain",
    "talk",
    "communicate",
    "shout",
    "script",
    "involuntary",
    "exclaim",
    "scream",
    "death",
];

/// A vocalization's name, or its abbreviation; none past the table
/// (`dialogue_get_vocalization_name`, which answers `<error>`).
pub fn vocalization_name(vocalization: i16, abbreviated: bool) -> Option<&'static str> {
    let names = VOCALIZATIONS.get(usize::try_from(vocalization).ok()?)?;
    Some(names[usize::from(abbreviated)])
}

/// The first vocalization of that name, matched exactly and never by its
/// abbreviation (`dialogue_get_vocalization_type_by_name`).
pub fn vocalization_by_name(name: &str) -> Option<usize> {
    VOCALIZATIONS.iter().position(|names| names[0] == name)
}

/// A priority's name; none past the table (`unit_get_speech_priority_name`,
/// which answers `<error>`).
pub fn speech_priority_name(priority: i16) -> Option<&'static str> {
    SPEECH_PRIORITIES
        .get(usize::try_from(priority).ok()?)
        .copied()
}

/// The priority of that name, matched exactly; `none` (0) for a name it
/// doesn't know (`unit_get_speech_priority_by_name`).
pub fn speech_priority_by_name(name: &str) -> usize {
    SPEECH_PRIORITIES
        .iter()
        .position(|priority| *priority == name)
        .unwrap_or(0)
}
