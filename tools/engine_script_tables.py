"""The tables the importer's port of the game's script fix-up
(hs_scenario_postprocess and hs_compile_postprocess) looks names and types
up in, generated from the sources so that they are the game's.

    python3 tools/engine_script_tables.py          # writes the tables
    python3 tools/engine_script_tables.py --check  # fails if they are stale

- the functions, in source/hs/hs.c's `hs_function_table` order, and the type
  each returns (tools/engine_script_signatures_reference.py compiles them);
- the external globals, in source/hs/hs_globals_external.c's
  `hs_external_globals` order, and each one's type;
- which types each type may be cast from (`hs_can_cast`, as
  tools/engine_script_cast_reference.py compiles it);
- hs.c's object type masks and tag reference groups, and the names of
  `hs_enum_table`'s enums.

They are written to engine/crates/import/src/script_tables.rs.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from harness import read  # noqa: E402

import engine_script_cast_reference as casts  # noqa: E402
import engine_script_signatures_reference as signatures  # noqa: E402

OUTPUT = ROOT / "engine" / "crates" / "import" / "src" / "script_tables.rs"

# hs_enum_table's enums: the array of names each one's entry points at,
# and the file that defines it
ENUMS = [
    ("global_game_difficulty_level_names", "source/game/game.c"),
    ("global_game_team_names", "source/game/game_allegiance.c"),
    ("global_ai_default_state_names", "source/ai/ai_scenario_definitions.c"),
    ("global_actor_type_names", "source/ai/actor_types.c"),
    ("global_hud_anchor_names", "source/interface/hud_definitions.c"),
]


def braced(source, declaration):
    """The text between the braces after `declaration`."""
    start = source.index("{", source.index(declaration)) + 1
    return source[start : source.index("};", start)]


def type_numbers():
    """hs.h's `enum hs_type`: each name's number."""
    body = braced(read("source/hs/hs.h"), "enum hs_type")
    names = re.findall(r"^\s*(_hs_\w+)", body, re.MULTILINE)
    return {name: number for number, name in enumerate(names)}


def externals():
    """Each external global's name and type, in the table's order."""
    source = read("source/hs/hs_globals_external.c")
    numbers = type_numbers()
    definitions = {
        name: (text, numbers[kind])
        for name, text, kind in re.findall(r'(\w+_definition)\s*=\s*\{\s*"([^"]*)",\s*(\w+)', source)
    }
    table = re.findall(r"&(\w+)", braced(source, "struct hs_external_global_definition *hs_external_globals["))
    return [definitions[name] for name in table]


def functions():
    """Each function's name and the type it returns, in the table's order."""
    found = []
    for line in signatures.reference().splitlines():
        if line.startswith("native "):
            _, name, returns = line.split(" ")[:3]
            found.append((name, int(returns)))
    return found


def cast_masks():
    """For each desired type, the bits of the types hs_can_cast lets be cast to it."""
    masks = [0] * 49
    for line in casts.reference().splitlines():
        if line.startswith("can "):
            _, actual, desired = line.split(" ")
            masks[int(desired)] |= 1 << int(actual)
    return masks


def hs_arrays():
    """hs.c's object type masks and tag reference groups."""
    hs_c = read("source/hs/hs.c")
    masks = re.findall(r"0x[0-9A-Fa-f]+", braced(hs_c, "word const hs_object_type_masks"))
    groups = re.findall(r"'(.{4})'", braced(hs_c, "tag const hs_tag_reference_type_group_tags"))
    return [int(mask, 16) for mask in masks], groups


def enum_names():
    """Each of hs_enum_table's enums' names."""
    return [re.findall(r'"([^"]*)"', braced(read(path), name + "[")) for name, path in ENUMS]


def string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def tables():
    """The Rust source of the tables."""
    found_functions = functions()
    found_externals = externals()
    masks, groups = hs_arrays()
    enums = enum_names()
    lines = [
        "//! The game's script tables, generated by tools/engine_script_tables.py",
        "//! from source/: do not edit.",
        "",
        "/// The functions, in the game's table's order, and the type each returns.",
        f"pub(crate) const FUNCTIONS: [(&str, i16); {len(found_functions)}] = [",
        *(f"    ({string(name)}, {returns})," for name, returns in found_functions),
        "];",
        "",
        "/// The external (engine) globals, in the game's table's order, and their types.",
        f"pub(crate) const EXTERNAL_GLOBALS: [(&str, i16); {len(found_externals)}] = [",
        *(f"    ({string(name)}, {kind})," for name, kind in found_externals),
        "];",
        "",
        "/// For each type, a bit for each type `hs_can_cast` lets be cast to it.",
        f"pub(crate) const CASTS: [u64; {len(cast_masks())}] = [",
        *(f"    {mask:#018x}," for mask in cast_masks()),
        "];",
        "",
        "/// The object types' masks of the object kinds each takes.",
        f"pub(crate) const OBJECT_TYPE_MASKS: [u16; {len(masks)}] = [",
        *(f"    {mask:#06x}," for mask in masks),
        "];",
        "",
        "/// The tag reference types' groups.",
        f"pub(crate) const TAG_GROUPS: [[u8; 4]; {len(groups)}] = [",
        *(f"    *b{string(group)}," for group in groups),
        "];",
        "",
        "/// The enum types' names.",
        f"pub(crate) const ENUMS: [&[&str]; {len(enums)}] = [",
        *("    &[" + ", ".join(string(name) for name in names) + "]," for names in enums),
        "];",
    ]
    return formatted("\n".join(lines) + "\n")


def formatted(source):
    """`source` as rustfmt (the formatter the tree is held to) writes it."""
    return subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the written tables are not the sources'")
    arguments = parser.parse_args()
    text = tables()
    if arguments.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit(f"{OUTPUT.relative_to(ROOT)} is stale: run tools/engine_script_tables.py")
        print("the script tables are the sources'")
        return
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
